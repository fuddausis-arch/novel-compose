def is_surname_start(name: str) -> bool:
    """是否以常见姓氏开头。"""
    return bool(name) and name[0] in COMMON_SURNAMES


def has_honorific_suffix(name: str) -> bool:
    """是否以称呼后缀结尾（王兄/李大人/赵将军）。"""
    if not name:
        return False
    for suf in HONORIFIC_SUFFIXES:
        if name.endswith(suf) and len(name) > len(suf):
            return True
    return False


def classify_name(name: str) -> str:
    """判定一个称呼/名字属于哪一类。

    返回 "kinship" / "generic_alias" / "person" / "unknown"。
    """
    name = (name or "").strip()
    if not name:
        return "unknown"
    if name in KINSHIP_TERMS:
        return "kinship"
    if name in GENERIC_PERSON_ALIASES:
        return "generic_alias"
    # 姓氏 + 称呼后缀 = 敬称（王兄、李大人、赵将军）
    if len(name) >= 2 and is_surname_start(name) and has_honorific_suffix(name):
        return "kinship"
    if is_surname_start(name):
        return "person"
    return "unknown"


def is_non_person_name(name: str) -> bool:
    """是否是称呼/别名（非人名）——validator 用它过滤疑似未知角色的误报。"""
    return classify_name(name) in ("kinship", "generic_alias")
