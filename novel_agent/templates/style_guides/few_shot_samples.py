def get_few_shot(scene_type: str) -> str:
    """按场景类型取few-shot对照样本。"""
    sample = FEW_SHOT_SAMPLES.get(scene_type)
    if not sample:
        return ""
    return (
        f"\n【文风示范·{scene_type}】\n"
        f"人类写法：{sample['human']}\n"
        f"AI写法(避免)：{sample['ai']}\n"
        f"要点：{sample['lesson']}\n"
    )


def get_few_shot_for_beat(beat_type: str = "") -> str:
    """根据beat类型推断场景类型，返回聚合的few-shot对照样本。

    始终附加"叙事"和"对话"样本，确保模型学会段落节奏和自然对话。
    """
    parts = []
    # 始终注入标准叙事和对话样本（最高优先级）
    parts.append(get_few_shot("叙事"))
    parts.append(get_few_shot("对话"))
    # 按beat类型追加场景样本
    if beat_type:
        beat_lower = beat_type.lower()
        if any(k in beat_lower for k in ("打脸", "碾压", "守护", "战斗", "高潮", "生存", "防御", "对峙", "智斗", "阻挡", "逃亡", "击杀", "厮杀", "搏杀")):
            parts.append(get_few_shot("战斗"))
        elif any(k in beat_lower for k in ("揭示", "共鸣", "情感", "识破", "感知", "发现")):
            parts.append(get_few_shot("情绪"))
        elif any(k in beat_lower for k in ("获取", "铺垫", "资源", "物资", "情报", "盟友", "汇合")):
            parts.append(get_few_shot("日常"))
        # 规则怪谈类beat额外注入规则设计样本
        if any(k in beat_lower for k in ("规则", "解谜", "试探", "怪谈")):
            parts.append(get_few_shot("主动决策"))
            parts.append(get_few_shot("情绪展示多样化"))
        # 决策/策略类beat注入主动决策样本
        if any(k in beat_lower for k in ("决策", "策略", "谈判", "权谋", "博弈", "分配")):
            parts.append(get_few_shot("主动决策"))
        # A8修复：移除"好大纲"样本——它是大纲写作样本，错注入正文写作prompt导致任务错位
    return "\n".join(p for p in parts if p)