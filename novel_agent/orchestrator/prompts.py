def build_writer_system_prompt() -> str:
    """构建 writer 系统提示词。

    优先用 PromptManager 从 prompts/sections.json 拼接——后台「Prompt 编排」页对
    writer 各 section 的编辑会即时生效；无配置或构建失败时回退硬编码
    WRITER_SYSTEM_PROMPT。默认 sections.json 的 writer 内容与 WRITER_SYSTEM_PROMPT
    逐字一致（见 prompts/sections.json 的 writer.rules/anti_ai），故默认行为不变。
    """
    try:
        from novel_agent.prompts.section_manager import PromptManager
        pm = PromptManager()
        built = pm.build_prompt("writer")
        if built.strip():
            return built
    except Exception as e:
        logger.warning("build_writer_system_prompt 构建失败，回退硬编码 WRITER_SYSTEM_PROMPT: %s", e)
    return WRITER_SYSTEM_PROMPT


